interface Neutrals {
  bgTertiary: string;
  borderSecondary: string;
  textTertiary: string;
  shadow: number; // rgba alpha base for shadows
}

function tokens(p: Palette, n: Neutrals, accentHover: string, accentActive: string): CssRules {
  return {
    "--bg-primary": p.background,
    "--bg-secondary": p.surfaceAlt,
    "--bg-tertiary": n.bgTertiary,
    "--border-primary": p.light.base,
    "--border-secondary": n.borderSecondary,
    "--text-primary": p.dark.base,
    "--text-secondary": p.secondary.base,
    "--text-tertiary": n.textTertiary,
    "--accent-primary": p.primary.base,
    "--accent-hover": accentHover,
    "--accent-active": accentActive,
    "--accent-focus": p.primary.focus,
    "--accent-text": p.primary.textOn,
    "--success": p.success.base,
    "--danger": p.danger.base,
    "--shadow-sm": `0 1px 2px 0 rgba(0, 0, 0, ${n.shadow})`,
    "--shadow-md": `0 4px 6px -1px rgba(0, 0, 0, ${n.shadow * 2}), 0 2px 4px -1px rgba(0, 0, 0, ${n.shadow})`,
    "--shadow-lg": `0 10px 15px -3px rgba(0, 0, 0, ${n.shadow * 2}), 0 4px 6px -2px rgba(0, 0, 0, ${n.shadow})`,
    "--shadow-xl": `0 20px 25px -5px rgba(0, 0, 0, ${n.shadow * 2}), 0 10px 10px -5px rgba(0, 0, 0, ${n.shadow})`,
    "--radius-sm": "6px",
    "--radius-md": "8px",
    "--radius-lg": "12px",
  };
}

